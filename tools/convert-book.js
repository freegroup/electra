function sitemap(pages) {
  const urls = ["", ...pages.map((p) => `${p.slug}.html`)]
    .map((u) => `  <url><loc>https://electra.academy/book/${u}</loc></url>`)
  return `<?xml version="1.0" encoding="UTF-8"?>\n`
       + `<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${urls.join("\n")}\n</urlset>\n`
}

function emitHtml(doc) {
  const pages = []
  for (const ch of doc) {
    if (/^Anhang$/i.test(ch.title)) continue

    // "Einführung" is a stub heading, not a topic - it belongs to the chapter.
    const intro = ch.sections.filter((s) => /^Einf/i.test(s.title))
    const topics = ch.sections.filter((s) => !/^Einf/i.test(s.title))

    const chapterNodes = [...ch.nodes, ...intro.flatMap((s) => s.nodes)]
    // A chapter page is written even with no prose of its own, as long as it has
    // topics - otherwise those topic pages have no parent to be reached from,
    // and a page nothing links to is a page Google does not find.
    if (chapterNodes.length || topics.length) {
      const lines = []
      htmlNodes(chapterNodes, lines)
      if (topics.length) {
        lines.push(`      <h2>In diesem Kapitel</h2>`, `      <ul class="chapterIndex">`)
        for (const t of topics) lines.push(`        <li><a href="./${slug(t.title)}.html">${htmlEsc(t.title)}</a></li>`)
        lines.push(`      </ul>`)
      }
      pages.push({ slug: slug(ch.title), title: ch.title,
                   description: firstSentence(chapterNodes), lines, kind: "chapter" })
    }

    for (const t of topics) {
      const lines = []
      htmlNodes(t.nodes, lines)
      pages.push({ slug: slug(t.title), title: t.title,
                   description: firstSentence(t.nodes), lines, kind: "section",
                   parent: slug(ch.title) })
    }
  }
  return pages
}

