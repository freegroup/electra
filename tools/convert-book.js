// ---------------------------------------------------------------------------
// A minimal zip reader. docx is a zip; we need three kinds of entry out of it
// and pulling in a dependency for that would be the only dependency this repo
// has.
// ---------------------------------------------------------------------------
function readZip(file) {
  const buf = fs.readFileSync(file)
  let eocd = -1
  for (let i = buf.length - 22; i >= 0 && i > buf.length - 66000; i--) {
    if (buf.readUInt32LE(i) === 0x06054b50) { eocd = i; break }
  }
  if (eocd < 0) throw new Error("kein zip: End-of-Central-Directory nicht gefunden")

  const count = buf.readUInt16LE(eocd + 10)
  let p = buf.readUInt32LE(eocd + 16)
  const entries = new Map()

  for (let n = 0; n < count; n++) {
    if (buf.readUInt32LE(p) !== 0x02014b50) throw new Error("zip-Verzeichnis beschaedigt")
    const method = buf.readUInt16LE(p + 10)
    const nameLen = buf.readUInt16LE(p + 28)
    const extraLen = buf.readUInt16LE(p + 30)
    const commentLen = buf.readUInt16LE(p + 32)
    const localOff = buf.readUInt32LE(p + 42)
    const name = buf.toString("utf8", p + 46, p + 46 + nameLen)
    entries.set(name, { method, localOff })
    p += 46 + nameLen + extraLen + commentLen
  }

  return {
    names: () => [...entries.keys()],
    read(name) {
      const e = entries.get(name)
      if (!e) throw new Error(`nicht im Archiv: ${name}`)
      let q = e.localOff
      if (buf.readUInt32LE(q) !== 0x04034b50) throw new Error("lokaler Header beschaedigt")
      const compSize = buf.readUInt32LE(q + 18)
      const rawSize = buf.readUInt32LE(q + 22)
      q += 30 + buf.readUInt16LE(q + 26) + buf.readUInt16LE(q + 28)
      // Streamed entries put the sizes in a trailing descriptor, so a zero here
      // means "read to the end and let inflate find the boundary".
      const body = buf.subarray(q, compSize ? q + compSize : undefined)
      if (e.method === 0) return body.subarray(0, rawSize || body.length)
      return zlib.inflateRawSync(body)
    },
  }
}

