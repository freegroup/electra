function main() {
  const zip = readZip(SRC)
  const xml = zip.read("word/document.xml").toString("utf8")
  const relsXml = zip.read("word/_rels/document.xml.rels").toString("utf8")
  const rels = {}
  for (const m of relsXml.matchAll(/Id="(rId\d+)"[^>]*Target="([^"]+)"/g)) rels[m[1]] = m[2]

  const { doc, counts, figures, manifest, terms } = parse(xml, rels)
  const texFiles = emitTex(doc)
  const pages = emitHtml(doc)

  const inZip = zip.names().filter((n) => n.startsWith("word/media/")).length
  const accounted = figures.inText + figures.inLayout + figures.titlePage

  console.log("Quelle:", SRC, "\n")

  let ok = true
  const check = (label, got, want) => {
    const good = got === want
    if (!good) ok = false
    console.log(`  ${good ? "ok  " : "FEHL"}  ${label.padEnd(22)} ${String(got).padStart(4)} / ${want}`)
  }
  check("Kapitel", counts.chapters, EXPECT.chapters)
  check("Abschnitte", counts.sections, EXPECT.sections)
  check("Wahrheitstabellen", counts.tables, EXPECT.tables)
  check("Layout-Tabellen", counts.layoutTables, EXPECT.layoutTables)
  check("Symbolzeichen", symCount, EXPECT.syms)
  check("Abbildungen zugeordnet", accounted, EXPECT.images)
  check("Abbildungen im Archiv", inZip, EXPECT.images)

  console.log(`\n  Abbildungen nach Fundort:`)
  console.log(`    im Text                ${String(figures.inText).padStart(4)}`)
  console.log(`    in Layout-Tabellen     ${String(figures.inLayout).padStart(4)}`)
  console.log(`    Titelseite (ungenutzt) ${String(figures.titlePage).padStart(4)}`)
  // Counted on the finished tree, not while parsing: table cells are read twice
  // (layout probe, then transpose), so a parse-time counter double-counts.
  const subs = {}
  const bump = (where, runs) => { subs[where] = (subs[where] || 0) + runs.filter((r) => r.sub).length }
  const walk = (nodes) => nodes.forEach((n) => {
    if (n.runs) bump(n.type, n.runs)
    if (n.type === "table") {
      n.head.forEach((h) => bump("table-kopf", h))
      n.body.forEach((r) => r.forEach((c) => bump("table-zellen", c)))
    }
    if (n.type === "layout") n.items.forEach((i) => {
      if (i.title) bump("layout", i.title)
      i.body.forEach((p) => bump("layout", p))
    })
  })
  doc.forEach((ch) => { walk(ch.nodes); ch.sections.forEach((s) => walk(s.nodes)) })
  const subTotal = Object.values(subs).reduce((a, b) => a + b, 0)
  console.log(`\n  Tiefstellungen erhalten: ${subTotal} / ${EXPECT.subscripts}`)
  for (const [k, v] of Object.entries(subs).sort((a, b) => b[1] - a[1])) {
    console.log(`    ${k.padEnd(22)} ${String(v).padStart(4)}`)
  }
  if (subTotal !== EXPECT.subscripts) ok = false
  console.log(`  generierte Verzeichnisabsaetze uebersprungen: ${counts.skipped}`)
  console.log(`\n  LaTeX-Kapiteldateien: ${texFiles.length}`)
  console.log(`  HTML-Seiten:          ${pages.length}`)
  console.log(`\n  ${pages.map((p) => `${p.kind === "chapter" ? "*" : " "} ${p.slug}`).join("\n  ")}`)

  if (!ok) {
    console.log("\nAbweichung gegen den erwarteten Bestand - es geht etwas verloren.")
    process.exit(1)
  }
  if (CHECK) { console.log("\n--check: nichts geschrieben."); return }

  for (const dir of Object.values(OUT)) fs.mkdirSync(dir, { recursive: true })

  for (const f of texFiles) fs.writeFileSync(path.join(OUT.tex, f.name), f.body + "\n")
  for (const p of pages) {
    fs.writeFileSync(path.join(OUT.html, `${p.slug}.html`),
      page({ title: p.title, description: p.description, slugName: p.slug,
             bodyLines: p.lines, tocMarkup: tocFor(pages, p.slug) }))
  }
  fs.writeFileSync(path.join(OUT.html, "index.html"), overviewPage(pages, terms))
  fs.writeFileSync(path.join(OUT.html, "sitemap.xml"), sitemap(pages))
  for (const name of zip.names()) {
    if (!name.startsWith("word/media/")) continue
    fs.writeFileSync(path.join(OUT.media, name.split("/").pop()), zip.read(name))
  }
  // Stage 2 renames by this, so image37.wmf reliably becomes abb-14.
  fs.writeFileSync(path.join(OUT.media, "figures.json"), JSON.stringify(manifest, null, 2) + "\n")

  console.log(`\ngeschrieben nach:\n  ${OUT.tex}\n  ${OUT.html}\n  ${OUT.media}`)
}

main()
