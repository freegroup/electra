// Word keeps its generated tables as normal paragraphs. Regenerated downstream.
const GENERATED = new Set([
  "Verzeichnis1", "Verzeichnis2", "Verzeichnis3",
  "Abbildungsverzeichnis", "Index1", "Index2", "Indexberschrift",
])

const cellsOf = (row) => (row.match(RE.cell) || [])
// Cells keep their runs. 166 of the 488 subscripts live in table headers, and
// flattening them to text turns every E<sub>1</sub> into "E1".
const parasOf = (cell) => (cell.match(RE.para) || []).map((p) => runsOf(p))
const parasText = (cell) => parasOf(cell).map(plain)

// Not every w:tbl is data. Seven of them are two-column layouts holding a
// circuit diagram on the left and its explanation on the right - the 7490 and
// 7492 divider variants. A figure inside a cell is the reliable tell.
function layoutTable(table, rels) {
  const rows = table.match(RE.row) || []
  const items = []
  for (const row of rows) {
    let figure = null
    const text = []
    for (const cell of cellsOf(row)) {
      const m = [...cell.matchAll(RE.image)].map((x) => rels[x[1]] || "").filter((t) => t.includes("media/"))
      if (m.length) figure = m[0].split("/").pop()
      // Runs, not text: the 7490 prose is full of R<sub>01</sub> and
      // Q<sub>A</sub> pin names.
      for (const runs of parasOf(cell)) if (plain(runs)) text.push(runs)
    }
    if (figure || text.length) items.push({ figure, title: text[0] || null, body: text.slice(1) })
  }
  return items
}

// The book uses two table layouts and they need opposite treatment.
//
//   column-major  header row, then cells that each stack a whole column of
//                 values. Long tables are split into several such rows, each a
//                 further chunk of the same columns - an 8-line truth table
//                 becomes two rows of four. Read row-wise this is nonsense.
//
//   row-major     ordinary table, one value per cell.
//
// The tell is how many paragraphs a body cell holds: more than one means the
// cell is a stacked column.
function dataTable(table) {
  const rows = table.match(RE.row) || []
  if (rows.length < 2) return null

  const head = cellsOf(rows[0]).map((c) => parasOf(c).flat())
  const cellFilled = (c) => parasOf(c).filter((runs) => plain(runs) !== "")

  // A trailing single-cell row ("usw.") is a note, not data - in either layout.
  const dataRows = []
  let note = null
  for (const r of rows.slice(1)) {
    const cells = cellsOf(r)
    if (cells.length === 1 && head.length > 1) {
      const t = parasText(cells[0]).join(" ").trim()
      if (t) note = t
      continue
    }
    dataRows.push(cells)
  }
  if (!dataRows.length) return null

  const columnMajor = cellFilled(dataRows[0][0] ?? "").length > 1
                   || cellFilled(dataRows[0][1] ?? "").length > 1

  const body = []
  if (columnMajor) {
    for (const cells of dataRows) {
      const columns = cells.map(cellFilled)
      const depth = Math.max(0, ...columns.map((c) => c.length))
      for (let i = 0; i < depth; i++) body.push(columns.map((c) => c[i] ?? []))
    }
  } else {
    for (const cells of dataRows) body.push(cells.map((c) => parasOf(c).flat()))
  }

  return { head, body, note, columnMajor }
}

function parse(xml, rels) {
  const body = xml.match(/<w:body>([\s\S]*)<\/w:body>/)[1]
  const blocks = body.match(RE.block) || []

  const doc = []          // chapters, each carrying its own nodes and sections
  let chapter = null
  let section = null

  const counts = { chapters: 0, sections: 0, tables: 0, layoutTables: 0, skipped: 0 }
  // Every one of the 72 figures is assigned a bucket. A plain count would go on
  // reporting "65 of 72" without ever saying where the other seven went.
  const figures = { inText: 0, inLayout: 0, titlePage: 0 }
  const allTerms = new Set()
  // Renaming map for stage 2: image37.wmf -> abb-14. Numbered in document
  // order, which is also the order the reader meets them in.
  const manifest = []
  const number = (source) => {
    manifest.push({ no: manifest.length + 1, source })
    return manifest.length
  }

  const target = () => (section ? section.nodes : chapter ? chapter.nodes : null)
  const mediaIn = (frag) => [...frag.matchAll(RE.image)]
    .map((m) => rels[m[1]] || "").filter((t) => t.includes("media/")).map((t) => t.split("/").pop())

  for (const block of blocks) {
    if (block.startsWith("<w:tbl")) {
      const rows = layoutTable(block, rels)
      const hasFigure = rows.some((r) => r.figure)

      if (hasFigure) {
        // Layout table: diagram left, explanation right. Not data.
        const items = rows.map((r) => (r.figure ? { ...r, no: number(r.figure) } : r))
        figures.inLayout += items.filter((i) => i.figure).length
        if (target()) { target().push({ type: "layout", items }); counts.layoutTables++ }
        continue
      }
      const t = dataTable(block)
      if (t && target()) {
        target().push({ type: "table", ...t })
        counts.tables++
      }
      continue
    }

    const style = (block.match(RE.style) || [])[1] || ""
    if (GENERATED.has(style)) { counts.skipped++; continue }

    const runs = runsOf(block)
    const text = plain(runs)
    const media = mediaIn(block)

    if (style === "berschrift1") {
      if (text === "Inhaltsverzeichnis") { chapter = null; section = null; continue }
      chapter = { type: "chapter", title: text, nodes: [], sections: [] }
      section = null
      doc.push(chapter)
      counts.chapters++
      continue
    }
    if (style === "berschrift2" && chapter) {
      section = { type: "section", title: text, nodes: [] }
      chapter.sections.push(section)
      counts.sections++
      continue
    }

    // Anything before the first chapter is the title page. It carries the cover
    // drawing, which the book sets separately and the website does not use.
    if (!target()) {
      for (const src of media) { number(src); figures.titlePage++ }
      continue
    }

    for (const src of media) {
      target().push({ type: "image", source: src, no: number(src) })
      figures.inText++
    }
    if (!text) continue

    const index = indexTerms(block)
    index.forEach((t) => allTerms.add(t))
    if (style === "Beschriftung") target().push({ type: "caption", text })
    else if (style === "Formel") target().push({ type: "formula", runs, index })
    else target().push({ type: "para", runs, index })
  }

  return { doc, counts, figures, manifest, terms: [...allTerms].sort((a, b) => a.localeCompare(b, "de")) }
}

// ---------------------------------------------------------------------------
// Emitters
// ---------------------------------------------------------------------------

function slug(s) {
  return s.toLowerCase()
    .replace(/\(.*?\)/g, " ")
    .replace(/ä/g, "ae").replace(/ö/g, "oe").replace(/ü/g, "ue").replace(/ß/g, "ss")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "")
}

const figName = (no) => `abb-${String(no).padStart(2, "0")}`

// Word numbers its own captions ("Tabelle 1:Logiktafel AND-Gatter"). LaTeX and
// the site number their own, so the prefix has to go or every figure ends up
// labelled twice - with the 2004 numbers.
const captionText = (s) => s.replace(/^(Abbildung|Tabelle)\s*\d+\s*:?\s*/i, "").trim()

// A caption is a sibling paragraph following the thing it describes. Hang it on
// that node instead, so the emitters can put it inside the float where LaTeX
// needs it - \caption outside a figure/table environment is an error.
function attachCaptions(nodes) {
  const out = []
  for (const n of nodes) {
    const prev = out[out.length - 1]
    if (n.type === "caption" && prev && (prev.type === "image" || prev.type === "table") && !prev.caption) {
      prev.caption = captionText(n.text)
      continue
    }
    out.push({ ...n })
  }
  return out
}

// --- LaTeX ---

const TEX_ESC = { "\\": "\\textbackslash{}", "&": "\\&", "%": "\\%", "$": "\\$", "#": "\\#",
                  "_": "\\_", "{": "\\{", "}": "\\}", "~": "\\textasciitilde{}", "^": "\\textasciicircum{}" }
// Logic operators via \ensuremath so they typeset in prose and in formulas
// alike, without depending on the text font carrying the glyph.
const TEX_MATH = { "\u2227": "\\ensuremath{\\wedge}", "\u2228": "\\ensuremath{\\vee}", "\u00ac": "\\ensuremath{\\lnot}" }

function tex(s) {
  return s.replace(/[\\&%$#_{}~^]/g, (c) => TEX_ESC[c])
          .replace(/[\u2227\u2228\u00ac]/g, (c) => TEX_MATH[c])
          // „ and “ pass through: lualatex reads Unicode, and flattening them
          // to ASCII would undo the German quotation marks set above.
          .replace(/”/g, "“")
}

function texRuns(runs) {
  return runs.map((r) => {
    let t = tex(r.text)
    if (r.sub) t = `\\textsubscript{${t}}`
    if (r.sup) t = `\\textsuperscript{${t}}`
    if (r.b) t = `\\textbf{${t}}`
    if (r.i) t = `\\emph{${t}}`
    return t
  }).join("")
}

function texNodes(rawNodes, out) {
  for (const n of attachCaptions(rawNodes)) {
    if (n.type === "image") {
      out.push("\\begin{figure}[htbp]", "  \\centering",
               `  \\includegraphics[width=.8\\linewidth]{media/${figName(n.no)}}`)
      if (n.caption) out.push(`  \\caption{${tex(n.caption)}}`)
      out.push("\\end{figure}", "")
      continue
    }
    // A caption with nothing before it is a standalone line, not a float label.
    if (n.type === "caption") { out.push(`\\emph{${tex(captionText(n.text))}}`, ""); continue }
    const idx = (n.index || []).map((t) => `\\index{${tex(t)}}`).join("")
    if (n.type === "para") out.push(texRuns(n.runs) + idx, "")
    else if (n.type === "formula") out.push("\\begin{quote}", `  ${texRuns(n.runs)}`, "\\end{quote}", idx ? idx : "", "")
    else if (n.type === "layout") {
      for (const it of n.items) {
        if (it.title) out.push(`\\subsection*{${texRuns(it.title)}}`, "")
        if (it.figure) {
          out.push("\\begin{figure}[htbp]", "  \\centering",
                   `  \\includegraphics[width=.7\\linewidth]{media/${figName(it.no)}}`,
                   "\\end{figure}", "")
        }
        for (const p of it.body) out.push(texRuns(p), "")
      }
    }
    else if (n.type === "table") {
      const cols = "c".repeat(n.head.length)
      out.push("\\begin{table}[htbp]", "  \\centering")
      if (n.caption) out.push(`  \\caption{${tex(n.caption)}}`)
      out.push(`  \\begin{tabular}{${cols}}`, "    \\toprule",
               `    ${n.head.map(texRuns).join(" & ")} \\\\`, "    \\midrule")
      for (const row of n.body) out.push(`    ${row.map(texRuns).join(" & ")} \\\\`)
      out.push("    \\bottomrule", "  \\end{tabular}")
      if (n.note) out.push(`  \\par\\medskip ${tex(n.note)}`)
      out.push("\\end{table}", "")
    }
  }
}

function emitTex(doc) {
  const files = []
  doc.forEach((ch, i) => {
    const out = [`\\chapter{${tex(ch.title)}}`, ""]
    texNodes(ch.nodes, out)
    for (const s of ch.sections) {
      out.push(`\\section{${tex(s.title)}}`, "")
      texNodes(s.nodes, out)
    }
    files.push({ name: `${String(i + 1).padStart(2, "0")}-${slug(ch.title)}.tex`, body: out.join("\n") })
  })
  return files
}

// --- HTML ---

const htmlEsc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")

function htmlRuns(runs) {
  return runs.map((r) => {
    let t = htmlEsc(r.text)
    if (r.sub) t = `<sub>${t}</sub>`
    if (r.sup) t = `<sup>${t}</sup>`
    if (r.b) t = `<b>${t}</b>`
    if (r.i) t = `<i>${t}</i>`
    return t
  }).join("")
}

function htmlNodes(rawNodes, out) {
  for (const n of attachCaptions(rawNodes)) {
    if (n.type === "image") {
      const label = htmlEsc(n.caption || "")
      out.push(`      <figure>`, `        <img src="media/${figName(n.no)}.svg" alt="${label}"/>`)
      if (n.caption) out.push(`        <figcaption>${label}</figcaption>`)
      out.push(`      </figure>`)
      continue
    }
    if (n.type === "caption") { out.push(`      <p class="caption">${htmlEsc(captionText(n.text))}</p>`); continue }
    if (n.type === "para") out.push(`      <p>${htmlRuns(n.runs)}</p>`)
    else if (n.type === "formula") out.push(`      <p class="formel">${htmlRuns(n.runs)}</p>`)
    else if (n.type === "layout") {
      for (const it of n.items) {
        if (it.title) out.push(`      <h3>${htmlRuns(it.title)}</h3>`)
        if (it.figure) {
          out.push(`      <figure><img src="media/${figName(it.no)}.svg" alt="${htmlEsc(plain(it.title || []))}"/></figure>`)
        }
        for (const p of it.body) out.push(`      <p>${htmlRuns(p)}</p>`)
      }
    }
    else if (n.type === "table") {
      out.push(`      <table>`)
      if (n.caption) out.push(`        <caption>${htmlEsc(n.caption)}</caption>`)
      out.push(`        <thead><tr>${n.head.map((h) => `<th>${htmlRuns(h)}</th>`).join("")}</tr></thead>`, `        <tbody>`)
      for (const row of n.body) out.push(`          <tr>${row.map((c) => `<td>${htmlRuns(c)}</td>`).join("")}</tr>`)
      out.push(`        </tbody>`, `      </table>`)
      if (n.note) out.push(`      <p class="caption">${htmlEsc(n.note)}</p>`)
    }
  }
}

function firstSentence(nodes) {
  const p = nodes.find((n) => n.type === "para")
  if (!p) return "Digitaltechnik verstehen und im Browser nachbauen."
  const t = plain(p.runs)
  return (t.length > 155 ? t.slice(0, 152).replace(/\s\S*$/, "") + "..." : t)
}

// The table of contents goes into every single page rather than being fetched.
// It costs a couple of kilobytes and buys the thing a book on the web needs
// most: every page linked from every other. Without internal links a crawler
// never reaches the depth of a 31-page work.
//
// `current` gets no link - a page linking to itself is noise.
function tocFor(pages, current) {
  const out = [`    <nav class="toc">`, `      <div class="tocTitle">Grundkurs Digitaltechnik</div>`, `      <ol>`]
  for (const ch of pages.filter((p) => p.kind === "chapter")) {
    const kids = pages.filter((p) => p.kind === "section" && p.parent === ch.slug)
    if (!kids.length) {
      out.push(`        <li>${link(ch, current)}</li>`)
      continue
    }
    // <details> statt eines JavaScript-Aufklappers: das Kapitel laesst sich
    // auch dann oeffnen, wenn das Bundle nicht laedt, und die Tastaturbedienung
    // bringt der Browser mit. Das Kapitel, in dem man gerade liest, steht
    // offen - unabhaengig davon, was gespeichert ist.
    const here = ch.slug === current || kids.some((k) => k.slug === current)
    out.push(`        <li><details data-chapter="${ch.slug}"${here ? " open" : ""}>`)
    out.push(`          <summary>${link(ch, current)}</summary>`)
    out.push(`          <ol>`)
    for (const k of kids) out.push(`            <li>${link(k, current)}</li>`)
    out.push(`          </ol>`)
    out.push(`        </details></li>`)
  }
  out.push(`      </ol>`)
  // Auf jeder Seite, nicht nur auf der Uebersicht: aus der Suche kommt man
  // immer mitten ins Buch, und das Ganze mitzunehmen soll von dort aus keine
  // Rueckwaertsnavigation kosten. Als Karte mit Titelbild, weil ein
  // verschenktes Buch nicht wie eine Fussnote aussehen sollte.
  const chapters = pages.filter((p) => p.kind === "chapter").length
  out.push(`      <a class="bookGift" href="./${PDF_NAME}" download>`)
  out.push(`        <img src="media/cover.jpg" alt="Titelseite: Grundkurs Digitaltechnik" width="120" height="170"/>`)
  out.push(`        <strong>Das ganze Buch als PDF</strong>`)
  out.push(`        <span>${chapters} Kapitel, kostenlos und ohne Anmeldung</span>`)
  out.push(`      </a>`)
  out.push(`    </nav>`)
  return out.join("\n")
}

