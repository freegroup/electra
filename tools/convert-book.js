// Symbol font, private use area. Anything not listed here throws rather than
// vanishing - see trap 2 in the header.
const SYMBOL = { F0D9: "\u2227", F0DA: "\u2228" }

const RE = {
  block: /<w:tbl>[\s\S]*?<\/w:tbl>|<w:p\b[^>]*\/>|<w:p\b[\s\S]*?<\/w:p>/g,
  run: /<w:r\b[^>]*>[\s\S]*?<\/w:r>/g,
  // w:t, not w:tabs - the lazy [^>]* form matches both and drags tab markup
  // into the text.
  text: /<w:t(?:\s[^>]*)?>([\s\S]*?)<\/w:t>/g,
  sym: /<w:sym\b[^>]*w:char="([0-9A-Fa-f]+)"[^>]*\/>/g,
  style: /w:pStyle w:val="([^"]+)"/,
  row: /<w:tr\b[\s\S]*?<\/w:tr>/g,
  cell: /<w:tc\b[\s\S]*?<\/w:tc>/g,
  para: /<w:p\b[\s\S]*?<\/w:p>/g,
  image: /<v:imagedata[^>]*r:id="(rId\d+)"/g,
}

function unescapeXml(s) {
  return s.replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&quot;/g, '"')
          .replace(/&apos;/g, "'").replace(/&amp;/g, "&")
}

let symCount = 0

// A paragraph as a list of formatted runs, in order.
function runsOf(frag) {
  const out = []
  for (const run of frag.match(RE.run) || []) {
    const props = (run.match(/<w:rPr>[\s\S]*?<\/w:rPr>/) || [""])[0]
    const style = {
      sub: /w:vertAlign w:val="subscript"/.test(props),
      sup: /w:vertAlign w:val="superscript"/.test(props),
      b: /<w:b\/>/.test(props),
      i: /<w:i\/>/.test(props),
    }
    // A tab carries no text of its own, but it does separate words. Dropping it
    // glued "E2" to "(sprich:" in every formula.
    let text = /<w:tab\/>/.test(run) ? " " : ""
    for (const m of run.matchAll(RE.text)) text += unescapeXml(m[1])
    for (const m of run.matchAll(RE.sym)) {
      const code = m[1].toUpperCase()
      const ch = SYMBOL[code]
      if (!ch) throw new Error(`unbekanntes Symbolzeichen w:char="${code}" - Zuordnung in SYMBOL ergaenzen`)
      text += ch
      symCount++
    }
    if (text) out.push({ ...style, text })
  }
  return germanQuotes(out)
}

// Word 2004 typed the same character for both ends of a quotation: 123 of the
// 124 quote marks in the manuscript are U+201C. German sets the opening one
// low. Pairing them by alternation within a paragraph is safe here because the
// book never leaves one unclosed.
function germanQuotes(runs) {
  let open = true
  for (const r of runs) {
    if (!r.text.includes("“")) continue
    r.text = r.text.replace(/“/g, () => (open = !open) ? "“" : "„")
  }
  return runs
}

const plain = (runs) => runs.map((r) => r.text).join("").replace(/\s+/g, " ").trim()

// Index entries survive as Word field instructions: XE "Halbaddierer". The
// generated index itself is thrown away with the rest of the generated matter,
// but these markers are the source it was built from, so both outputs can
// regenerate it with their own page numbers.
//
// The instruction is often split across several runs mid-word, so the field has
// to be reassembled before it is read - matching run by run yields fragments of
// XML instead of terms.
function indexTerms(frag) {
  const terms = []
  for (const field of frag.split(/<w:fldChar[^>]*w:fldCharType="begin"[^>]*\/>/).slice(1)) {
    const body = field.split(/<w:fldChar[^>]*w:fldCharType="(?:separate|end)"[^>]*\/>/)[0]
    let instr = ""
    for (const m of body.matchAll(/<w:instrText(?:\s[^>]*)?>([\s\S]*?)<\/w:instrText>/g)) instr += unescapeXml(m[1])
    const xe = instr.match(/^\s*XE\s+"([^"]+)"/)
    if (xe) terms.push(xe[1].trim())
  }
  return terms
}

