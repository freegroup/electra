#!/usr/bin/env node
//
// One-shot conversion of the "Grundkurs" manuscript into the two formats it
// will live in from now on: LaTeX for the printed book, HTML for the website.
//
// Runs ONCE. After that both outputs are hand-maintained and this file stays
// only as the record of how they came to be - so it has to produce output you
// can edit further, not a scaffold.
//
// Three traps in the source document, all found by measuring rather than
// assuming, all of which corrupt the text silently if you miss them:
//
//   1. Truth tables are COLUMN-MAJOR. A 2x3 table where row 2 holds three
//      cells, each stacking a whole column of values. Read row-wise you get
//      "0 0 1 1 | 0 1 0 1" instead of an AND table. They have to be transposed.
//
//   2. The AND and OR operators are NOT text. They are
//      <w:sym w:font="Symbol" w:char="F0D9"/> and F0DA - Symbol-font private
//      use codepoints. Every naive w:t extraction drops them and leaves
//      "A = E1  E2", which reads as if the operator were a space. 27 of them.
//
//   3. Subscripts are run properties, not characters. Without them every
//      E1/E2 collapses to E1. The document holds 488 w:vertAlign marks, but
//      only 448 belong to text: the other 40 sit in w:pPr/w:rPr, which is the
//      formatting of the paragraph MARK - what the next typed character would
//      get. There is nothing there to carry over, so 448 is the whole of it.
//
// Word also stores its generated matter as ordinary paragraphs - table of
// contents, list of figures, index. Those are dropped and regenerated by
// LaTeX/the site, otherwise the page numbers of 2004 travel along.
//
//   node tools/convert-book.js --check    parse and report, write nothing
//   node tools/convert-book.js            write all outputs

